namespace Subspace;

/// <summary>
/// Simple 5×7 pixel-art font renderer. No SpriteFont or Content Pipeline required.
/// </summary>
public class PixelFont
{
    private readonly Texture2D _pixel;

    /// <summary>Character width including 1-pixel spacing gap.</summary>
    public const int CharW = 6;

    /// <summary>Character height including 2-pixel spacing gap.</summary>
    public const int CharH = 9;

    public PixelFont(Texture2D pixel) => _pixel = pixel;

    /// <summary>Draw a string at (x, y) in the current spriteBatch coordinate system.</summary>
    public void DrawString(SpriteBatch sb, string text, int x, int y, Color color, int scale = 1)
    {
        int cx = x;
        foreach (char c in text)
        {
            if (c == '\n')
            {
                cx = x;
                y += CharH * scale;
                continue;
            }

            int idx = c - 32;
            if (idx >= 0 && idx < FontData.Length / 7)
            {
                for (int row = 0; row < 7; row++)
                {
                    byte bits = FontData[idx * 7 + row];
                    for (int col = 0; col < 5; col++)
                    {
                        if ((bits & (0x10 >> col)) != 0)
                            sb.Draw(_pixel, new Rectangle(cx + col * scale, y + row * scale, scale, scale), color);
                    }
                }
            }

            cx += CharW * scale;
        }
    }

    /// <summary>Returns the pixel width of the string at the given scale.</summary>
    public int MeasureWidth(string text, int scale = 1) => text.Length * CharW * scale;

    /// <summary>Returns the pixel height of one line at the given scale.</summary>
    public int LineHeight(int scale = 1) => CharH * scale;

